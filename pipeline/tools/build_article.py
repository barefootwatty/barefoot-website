def sync_media_index():
    """Rewrite the generated article cards in the Media Centre library grid.

    Without this the articles exist but nothing links to them, which for a
    library built to be found by search is the whole ballgame.
    """
    path = os.path.join(SITE, "media.html")
    html = open(path, encoding="utf-8").read()
    if LIB_START not in html:
        print("  ! no ARTICLES markers in media.html — cards not synced")
        return 0

    cards = []
    for name in sorted(os.listdir(SRC_DIR)):
        if not name.endswith(".txt"):
            continue
        meta, _ = parse(os.path.join(SRC_DIR, name))
        slug = name[:-4]
        img, _w, _h, _s = MODULE_IMG.get(meta["module"], DEFAULT_IMG)
        alt = MODULE_ALT.get(meta["module"], DEFAULT_ALT)
        sizes = "(max-width:520px) 100vw, (max-width:840px) 50vw, 33vw"
        cards.append(f"""
      <a class="libcard" data-type="article" href="media/article-{slug}.html">
        <div class="thumb">
          <picture>
            <source type="image/avif" srcset="assets/img/{img}-640.avif 640w, assets/img/{img}-1000.avif 1000w" sizes="{sizes}">
            <img src="assets/img/{img}-640.jpg" srcset="assets/img/{img}-640.jpg 640w, assets/img/{img}-1000.jpg 1000w" sizes="{sizes}" width="1600" height="900" alt="{attr(alt)}" loading="lazy" decoding="async">
          </picture>
        </div>
        <div class="body">
          <span class="type">Know-How</span>
          <h3>{entities(meta['title'])}</h3>
          <p>{entities(meta['ogdesc'])}</p>
          <span class="go">Read the article &rarr;</span>
        </div>
      </a>
""")

    start = html.index(LIB_START) + len(LIB_START)
    end = html.index(LIB_END)
    html = html[:start] + "".join(cards) + "\n      " + html[end:]
    open(path, "w", encoding="utf-8").write(html)
    print(f"  media.html: {len(cards)} article card(s) synced")
    return len(cards)


def sync_sitemap():
    """Every article gets a sitemap entry. Crawlers should not have to guess."""
    path = os.path.join(SITE, "sitemap.xml")
    xml = open(path, encoding="utf-8").read()
    added = 0
    for name in sorted(os.listdir(SRC_DIR)):
        if not name.endswith(".txt"):
            continue
        loc = f"{PROD}/media/article-{name[:-4]}"
        if f"<loc>{loc}</loc>" in xml:
            continue
        xml = xml.replace(
            "</urlset>",
            f'  <url><loc>{loc}</loc><priority>0.6</priority></url>\n</urlset>', 1)
        added += 1
    if added:
        open(path, "w", encoding="utf-8").write(xml)
    print(f"  sitemap.xml: {added} article URL(s) added")
    return added


def main():
    args = [a for a in sys.argv[1:] if a != "--all"]
    if "--all" in sys.argv or not args:
        args = sorted(os.path.join(SRC_DIR, f) for f in os.listdir(SRC_DIR)
                      if f.endswith(".txt"))
    os.makedirs(OUT_DIR, exist_ok=True)
    index = title_index()
    for path in args:
        slug = os.path.splitext(os.path.basename(path))[0]
        out = os.path.join(OUT_DIR, f"article-{slug}.html")
        with open(out, "w", encoding="utf-8") as fh:
            fh.write(build(path, index))
        print(f"  {slug}")
    print(f"built {len(args)} article page(s) -> {OUT_DIR}")
    sync_media_index()
    sync_sitemap()


if __name__ == "__main__":
    main()
